import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs'
import { createServer } from 'node:net'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

export const WEB_SEARCH_PATCH_BEGIN = '# BEGIN FREECODE MANAGED WEB SEARCH'
export const WEB_SEARCH_PATCH_END = '# END FREECODE MANAGED WEB SEARCH'

export interface WebSearchHomeOptions {
  homeDir: string
  /** The resources/freecode directory holding searxng-search/ and searxng-runtime/. */
  resourcesDir: string
  /** Port for this boot. Omit to pick a free loopback port. */
  port?: number
  platform?: NodeJS.Platform
}

export interface WebSearchHomeState {
  configPath: string
  enabled: boolean
  /** True only when the block was written, so the sidecar must run. */
  active: boolean
  port?: number
  runtimeDir: string
  settingsPath: string
  tempDir: string
}

function writeAtomic(path: string, contents: string): void {
  const temporary = `${path}.tmp-${process.pid}-${Date.now()}`
  writeFileSync(temporary, contents, { encoding: 'utf8', mode: 0o600 })
  renameSync(temporary, path)
}

function readEnabled(path: string): boolean {
  if (!existsSync(path)) return true
  try {
    return (JSON.parse(readFileSync(path, 'utf8')) as { enabled?: unknown }).enabled !== false
  } catch {
    return true
  }
}

export function freeLoopbackPort(): Promise<number> {
  return new Promise((resolve, reject) => {
    const server = createServer()
    server.once('error', reject)
    server.listen(0, '127.0.0.1', () => {
      const address = server.address()
      const port = typeof address === 'object' && address !== null ? address.port : 0
      server.close(() => (port > 0 ? resolve(port) : reject(new Error('no free loopback port'))))
    })
  })
}

function renderBlock(pluginUrl: string, port: number): string {
  return [
    WEB_SEARCH_PATCH_BEGIN,
    '# Generated by FreeCode on each boot. Edit web-search/searxng.json to disable this.',
    '- insert:',
    '    - id: web-search-searxng',
    `      name: ${JSON.stringify(pluginUrl)}`,
    '      config:',
    `        baseURL: ${JSON.stringify(`http://127.0.0.1:${port}`)}`,
    '- id: web',
    '  config:',
    '    searchProvider: searxng',
    '    fetchProvider: http',
    WEB_SEARCH_PATCH_END,
    '',
  ].join('\n')
}

function mergeBlock(existing: string, block: string | undefined): string {
  const pattern = new RegExp(`${WEB_SEARCH_PATCH_BEGIN}[\\s\\S]*?${WEB_SEARCH_PATCH_END}\\r?\\n?`, 'm')
  const stripped = existing.replace(pattern, '').trimEnd()
  // An empty or comments-only patch fails DSH boot, and `[]` cannot take list rows.
  const base = stripped === '[]' ? '' : stripped
  if (block === undefined) return base.length === 0 ? '[]\n' : `${base}\n`
  return base.length === 0 ? block : `${base}\n\n${block}`
}

/**
 * Refresh only the managed patch block. Run it after ensureEmbeddedMcpConfig and
 * before the harness starts. A row naming a missing file would fail DSH boot, so
 * the block is written only when the plugin and the Python payload both exist.
 */
export async function ensureManagedWebSearch(options: WebSearchHomeOptions): Promise<WebSearchHomeState> {
  const dir = join(options.homeDir, 'web-search')
  const tempDir = join(dir, 'tmp')
  const configPath = join(dir, 'searxng.json')
  const patchPath = join(options.homeDir, 'cordis.patch.yml')
  const source = join(options.resourcesDir, 'searxng-search')
  const pluginPath = join(source, 'index.mjs')
  const settingsPath = join(source, 'settings.yml')
  const runtimeDir = join(options.resourcesDir, 'searxng-runtime')
  mkdirSync(tempDir, { recursive: true })

  const enabled = readEnabled(configPath)
  writeAtomic(configPath, `${JSON.stringify({ version: 1, enabled }, null, 2)}\n`)

  const installed = (options.platform ?? process.platform) === 'win32'
    && existsSync(pluginPath)
    && existsSync(settingsPath)
    && existsSync(join(runtimeDir, 'python', 'python.exe'))
  const active = enabled && installed
  const port = active ? options.port ?? await freeLoopbackPort() : undefined
  const block = active ? renderBlock(pathToFileURL(pluginPath).href, port as number) : undefined
  const existing = existsSync(patchPath) ? readFileSync(patchPath, 'utf8') : ''
  writeAtomic(patchPath, mergeBlock(existing, block))
  return { configPath, enabled, active, port, runtimeDir, settingsPath, tempDir }
}
