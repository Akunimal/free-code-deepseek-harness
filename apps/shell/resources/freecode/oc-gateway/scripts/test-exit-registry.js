'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { ExitRegistry, createAttempt, finishAttempt } = require('./exit-registry');
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'oc-exit-state-'));
let now = Date.now();
try {
  const state = new ExitRegistry(home, { clock: () => now });
  const a = 'a'.repeat(32), b = 'b'.repeat(32), c = 'c'.repeat(32);
  createAttempt(home, a, 'alpha', 60_000);
  createAttempt(home, b, 'beta', 60_000);
  state.connected(a, 'socks5h://127.0.0.1:101');
  state.connected(b, 'socks5h://127.0.0.1:102');
  assert.equal(state.pin(a), 'socks5h://127.0.0.1:101');
  assert.equal(state.pin(b), 'socks5h://127.0.0.1:102');
  assert.equal(finishAttempt(home, a, { outcome: 'quota', status: 429, upstreamResponded: true, retryAfterMs: 3600_000 }).address, state.pin(a));
  finishAttempt(home, b, { outcome: 'success', status: 200 });
  state.collect();
  const until = state.until('socks5h://127.0.0.1:101', 'alpha');
  assert.ok(until >= now + 3590_000);
  assert.equal(state.until('socks5h://127.0.0.1:101', 'beta'), 0);
  const reloaded = new ExitRegistry(home, { clock: () => now });
  assert.equal(reloaded.until('socks5h://127.0.0.1:101', 'alpha'), until);
  assert.ok(reloaded.state.exits['socks5h://127.0.0.1:102'].models.beta.generationConfirmedAt);
  assert.equal(reloaded.transportFailed('dead') - now, 5000);
  reloaded.connected(null, 'dead');
  assert.equal(reloaded.transportFailed('dead') - now, 10000);
  for (let i = 0; i < 15; i++) reloaded.transportFailed('dead');
  assert.equal(reloaded.until('dead', 'any') - now, 1800_000);
  now = until + 1;
  assert.ok(reloaded.until('socks5h://127.0.0.1:101', 'alpha') < now);
  createAttempt(home, c, 'alpha', 1);
  assert.equal(reloaded.lease(c), null, 'expired leases cannot dial');
  reloaded.collect();
  assert.deepEqual(fs.readdirSync(path.join(home, 'data', 'exit-attempts')), []);
  const noTunnel = 'd'.repeat(32);
  createAttempt(home, noTunnel, 'alpha', 60_000);
  assert.equal(finishAttempt(home, noTunnel, { outcome: 'cancelled', status: 499 }), null);
  assert.deepEqual(fs.readdirSync(path.join(home, 'data', 'exit-attempts')), [], 'front outage cannot accumulate unattached feedback');
  console.log('PASS concurrent identities, per-model quota, persisted reset, generation evidence, transport backoff/cap and lease expiry');
} finally { fs.rmSync(home, { recursive: true, force: true }); }
